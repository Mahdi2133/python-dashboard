FA = '۰۱۲۳۴۵۶۷۸۹'


def fa(s):
    """رقم‌های لاتین را فارسی می‌کند و نقطه‌ی اعشار را به ممیز."""
    out = []
    for ch in str(s):
        if ch.isdigit():
            out.append(FA[int(ch)])
        elif ch == '.':
            out.append('٫')
        else:
            out.append(ch)
    return ''.join(out)


